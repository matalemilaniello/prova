/**
 * Ritmo · ricette.
 *
 * Le quantità sono la porzione di riferimento del giorno di palestra. Le righe con `carbScaled`
 * (pane, pasta, riso, cereali, patate) si adattano al tipo di giorno con `carbFactor`:
 * calcio × 1,25, palestra × 1, leggero × 0,9, riposo × 0,75.
 *
 * Criteri: cucina italiana vera e veloce (montaggio in 15 minuti al massimo, oppure preparazione
 * della domenica), proteine 30-45 g nei pasti principali, vegetali comodi (surgelati, insalate in busta,
 * legumi in barattolo, frutta che non va preparata), pochi prodotti ultra-processati.
 * Nei giorni di calcio la merenda è un pre-calcio digeribile (poca fibra e pochi grassi, 2-3 ore prima)
 * e la cena è una cena di recupero veloce, con carboidrati e proteine.
 *
 * Gli id restano quelli di sempre anche quando una ricetta cambia ingredienti (lo skyr diventato yogurt greco, il
 * muesli diventato avena, gallette e clementine diventate pane e kiwi): li usano le sostituzioni salvate nel diario.
 * Il nome mostrato è `name`.
 * La frutta è quella che si trova tutto l'anno (mela, banana, kiwi, frutti di bosco surgelati): il menù gira in ogni
 * stagione, quindi niente frutti che spariscono per metà dell'anno, come le clementine da aprile a ottobre.
 * Le alternative (`swaps`) mettono per prime quelle che usano gli stessi prodotti del menù: chi sostituisce un
 * pasto non allunga la spesa.
 */
import type { IngredientLine, PortionUnit, Recipe } from '../domain/types';

type LineOpts = { carb?: boolean; note?: string };

/** Riga di ingrediente: alimento, quantità, unità; `carb` = si adatta al tipo di giorno. */
function i(foodId: string, qty: number, unit: PortionUnit, opts: LineOpts = {}): IngredientLine {
  const line: IngredientLine = { foodId, qty, unit };
  if (opts.carb) line.carbScaled = true;
  if (opts.note) line.note = opts.note;
  return line;
}

